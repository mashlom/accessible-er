/**
 * Downloads Lottie animations for every emoji the app uses.
 *
 * Source: Google's **Noto Animated Emoji** (CC BY 4.0) —
 * https://googlefonts.github.io/noto-emoji-animation/
 * Files land in `public/anim/<codepoints>.json` and are fetched lazily at
 * runtime; a manifest is written to `src/data/animations.ts` so the app only
 * asks for icons that actually exist upstream (coverage is partial).
 *
 * Re-run after adding emoji to the content:  node scripts/fetch-animations.mjs
 */
import { readFile, writeFile, mkdir, readdir, stat } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT_DIR = join(ROOT, 'public', 'anim')
const MANIFEST = join(ROOT, 'src', 'data', 'animations.ts')
const BASE = 'https://fonts.gstatic.com/s/e/notoemoji/latest'

/** Files scanned for emoji: the shared content plus the story concept's UI. */
const SCAN_DIRS = [
  join(ROOT, 'src', 'data'),
  join(ROOT, 'src', 'concepts', 'story'),
  join(ROOT, 'src', 'concepts', 'talk'),
]

/**
 * A few upstream files are enormous for what they are (🏁 is 320 KB). An icon
 * is never worth that on a phone in an ER waiting room — skip it and let the
 * static glyph stand in.
 */
const MAX_BYTES = 150 * 1024

const EMOJI_RE =
  /\p{Extended_Pictographic}️?(?:‍\p{Extended_Pictographic}️?)*/gu

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) yield* walk(path)
    else if (/\.(tsx?|css)$/.test(entry.name)) yield path
  }
}

function codepoints(emoji) {
  return [...emoji].map((c) => c.codePointAt(0).toString(16)).join('_')
}

/** Noto is inconsistent about VS16, so try the sequence with and without it. */
function candidates(emoji) {
  const withVs = codepoints(emoji)
  const withoutVs = codepoints([...emoji].filter((c) => c !== '️').join(''))
  return [...new Set([withVs, withoutVs])]
}

const found = new Set()
for (const dir of SCAN_DIRS) {
  for await (const file of walk(dir)) {
    const text = await readFile(file, 'utf8')
    for (const m of text.matchAll(EMOJI_RE)) found.add(m[0])
  }
}

await mkdir(OUT_DIR, { recursive: true })

const available = []
const missing = []
const tooBig = []
let bytes = 0

for (const emoji of [...found].sort()) {
  let saved = null
  for (const cp of candidates(emoji)) {
    const res = await fetch(`${BASE}/${cp}/lottie.json`)
    if (!res.ok) continue
    const body = await res.text()
    try {
      JSON.parse(body) // some CDNs answer 200 with an HTML error page
    } catch {
      continue
    }
    const size = Buffer.byteLength(body)
    if (size > MAX_BYTES) {
      tooBig.push(`${emoji} (${(size / 1024).toFixed(0)}KB)`)
      continue
    }
    await writeFile(join(OUT_DIR, `${cp}.json`), body)
    bytes += size
    saved = cp
    break
  }
  if (saved) available.push([emoji, saved])
  else missing.push(emoji)
}

const lines = available.map(([emoji, cp]) => `  '${emoji}': '${cp}',`).join('\n')
await writeFile(
  MANIFEST,
  `/**
 * Emoji → Lottie file id, generated by \`scripts/fetch-animations.mjs\`.
 * DO NOT EDIT BY HAND — re-run the script instead.
 *
 * Animations are Google's Noto Animated Emoji, licensed CC BY 4.0.
 * Files live in \`public/anim/<id>.json\` and are fetched on demand.
 * Emoji with no upstream animation are simply absent here, and the UI
 * falls back to the static glyph.
 */
export const animatedEmoji: Record<string, string> = {
${lines}
}

export function animationUrl(emoji: string): string | null {
  const id = animatedEmoji[emoji]
  return id ? \`anim/\${id}.json\` : null
}
`,
)

console.log(`saved   ${available.length} animations (${(bytes / 1024).toFixed(0)} KB)`)
console.log(`no anim ${missing.length}: ${missing.join(' ')}`)
if (tooBig.length) console.log(`skipped (over ${MAX_BYTES / 1024}KB): ${tooBig.join(' ')}`)
const dirSize = (await Promise.all(
  (await readdir(OUT_DIR)).map(async (f) => (await stat(join(OUT_DIR, f))).size),
)).reduce((a, b) => a + b, 0)
console.log(`public/anim total: ${(dirSize / 1024).toFixed(0)} KB`)
